def _merge_indices(primary: list[int], extra: list[int], limit: int) -> list[int]:
    """Union ordonnée : `primary` garde la priorité (plancher déterministe),
    `extra` ne complète que s'il reste de la place sous `limit`."""
    merged = list(primary)
    for index in extra:
        if index not in merged:
            merged.append(index)
        if len(merged) >= limit:
            break
    return merged[:limit]


def _fold(text: str) -> str:
    """Casse et accents neutralisés, pour comparer un nom d'entreprise tel
    que reformulé par le LLM à celui du profil sans faux négatif trivial."""
    decomposed = unicodedata.normalize("NFKD", text)
    return "".join(c for c in decomposed if not unicodedata.combining(c)).lower()


def _period_signature(period: str) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """Normalise une période en années/mois même si le LLM traduit les mois."""
    words = re.findall(r"[a-z]+|\d{4}", _fold(period))
    years = tuple(int(word) for word in words if re.fullmatch(r"\d{4}", word))
    months = tuple(_MONTHS[word] for word in words if word in _MONTHS)
    return years, months


def _experience_identity(meta: dict) -> tuple[str, str, str]:
    return (
        _fold(meta.get("company", "")),
        _fold(meta.get("period", "")),
        _fold(meta.get("role", "")),
    )


def _experience_order(period: str) -> tuple[int, int]:
    years, months = _period_signature(period)
    return (years[0] if years else 0, months[0] if months else 0)


def offer_text(offre: dict) -> str:
    """Contexte d'offre explicite, réutilisable pour CV et candidature.

    Les métadonnées restent séparées de la description afin que le modèle
    et les générateurs déterministes ne confondent pas le texte d'annonce
    avec des faits du profil candidat.
    """
    entreprise = offre.get("entreprise") or offre.get("company") or {}
    if isinstance(entreprise, dict):
        entreprise = entreprise.get("nom") or entreprise.get("name")
    origine = offre.get("origineOffre") or {}
    partenaires = origine.get("partenaires") or []
    partenaire_url = next(
        (p.get("url") for p in partenaires if isinstance(p, dict) and p.get("url")),
        None,
    )
    application = offre.get("application") or {}
    values = [
        _single_line(offre.get("intitule") or offre.get("title")),
        f"Entreprise : {_single_line(entreprise)}" if entreprise else None,
        f"Lieu : {_single_line((offre.get('lieuTravail') or {}).get('libelle') if isinstance(offre.get('lieuTravail'), dict) else offre.get('location'))}" if (offre.get("lieuTravail") or offre.get("location")) else None,
        f"Contrat : {_single_line(offre.get('typeContrat') or offre.get('contract_type'))}" if (offre.get("typeContrat") or offre.get("contract_type")) else None,
        f"Date de publication : {_single_line(offre.get('dateCreation') or offre.get('posted_at'))}" if (offre.get("dateCreation") or offre.get("posted_at")) else None,
        f"Date limite : {_single_line(offre.get('dateLimiteDePotentiel') or offre.get('dateLimite') or offre.get('dateFin') or offre.get('deadline') or application.get('deadline'))}" if (offre.get("dateLimiteDePotentiel") or offre.get("dateLimite") or offre.get("dateFin") or offre.get("deadline") or application.get("deadline")) else None,
        f"Lien de candidature : {_single_line(application.get('url') or offre.get('url') or offre.get('urlOffre') or partenaire_url or origine.get('urlOrigine'))}" if (application.get("url") or offre.get("url") or offre.get("urlOffre") or partenaire_url or origine.get("urlOrigine")) else None,
        "Description de l'offre :",
        _single_line(offre.get("description")),
    ]
    return "\n".join(value for value in values if value)


def _single_line(value: object) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def _offer_context_value(context: str, label: str) -> str:
    prefix = f"{label.casefold()} :"
    for line in context.splitlines():
        if line.casefold().startswith(prefix):
            return _single_line(line[len(prefix):])
    return ""


def format_cv_text(cv: CVContent) -> str:
    """Rendu texte lisible d'un `CVContent`, pour l'affichage/lecture en
    chat, pas un vrai document mis en page (voir le skill docx pour un
    CV final à envoyer)."""
    lignes = [cv.profil, "", "EXPÉRIENCES"]
    for e in cv.experiences:
        lignes.append(f"  {e.role} chez {e.entreprise} ({e.periode})")
        lignes.extend(f"    • {p}" for p in e.puces)
    if cv.projets:
        lignes += ["", "PROJETS"]
        lignes.extend(f"  {p.titre} : {p.description}" for p in cv.projets)
    lignes += ["", "COMPÉTENCES"]
    for categorie, items in cv.competences.items():
        lignes.append(f"  {categorie} : {', '.join(items)}")
    lignes += ["", "FORMATION"]
    lignes.extend(f"  {f}" for f in cv.formation)
    if cv.certifications:
        lignes += ["", "CERTIFICATIONS"]
        lignes.extend(f"  {c}" for c in cv.certifications)
    if cv.langues:
        lignes += ["", "LANGUES : " + ", ".join(cv.langues)]
    if cv.centres_interet:
        lignes += ["CENTRES D'INTÉRÊT : " + ", ".join(cv.centres_interet)]
    return "\n".join(lignes)


class ApplicationWriter:
    def __init__(
        self,
        profil_manager: ProfilManager | None = None,
        llm: LLMClient | None = None,
    ) -> None:
        self.profil_manager = profil_manager or ProfilManager()
        # `keep_alive` COURT (`KEEP_ALIVE_OCCASIONAL`) : CV/LM sont des
        # usages BURSTY et peu fréquents (une candidature de temps en
        # temps, pas en continu), contrairement au modèle léger utilisé
        # pour presque tout le reste de la conversation. Mesuré sur un
        # GPU 6 Go (RTX 3060 Laptop) que ce modèle et le modèle léger ne
        # coexistent JAMAIS en VRAM (`ollama ps` confirme une éviction
        # complète, pas juste un ralentissement) : un `keep_alive` long
        # (30 min, par défaut) laisserait ce modèle lourd occuper la
        # VRAM bien après la rédaction, forçant le modèle léger à se
        # recharger pour la toute PROCHAINE action côté chat.
        self.llm = llm or LLMClient(model=settings.llm_model_career, keep_alive=KEEP_ALIVE_OCCASIONAL)

    def reload_llm(self) -> None:
        """Reconstruit `self.llm` depuis `settings.llm_model_career`
        COURANT. Nécessaire car `ApplicationWriter` est un singleton de
        longue durée côté API (`aelyn_api.deps.get_application_writer`,
        `ConversationalAgent.application_writer`) : son `LLMClient` est
        construit UNE SEULE FOIS avec le modèle d'alors, un `PATCH
        /settings` qui change `llm_model_career` ne s'y refléterait donc
        jamais tout seul. Appelée par le routeur settings juste après avoir
        persisté le nouveau modèle, sur CHAQUE instance vivante, pour un
        changement effectif immédiatement plutôt qu'au prochain
        redémarrage de l'API. Pas d'appel réseau ici : construire un
        `LLMClient` ne fait que préparer le client Ollama, le modèle n'est
        sollicité qu'au prochain `draft_cv`/`draft_cover_letter_stream`."""
        self.llm = LLMClient(model=settings.llm_model_career, keep_alive=KEEP_ALIVE_OCCASIONAL)

    def reload_profile(self) -> None:
        """Recharge `self.profil_manager` depuis `profil.json` sur disque.

        Même raison que `reload_llm` ci-dessus : `ProfilManager` lit le
        fichier une seule fois, à l'import du module `profil_manager`
        (`profil_json` global) ET à la construction de `ApplicationWriter`
        (singleton). Après `PUT /career/profile` (aelyn-api) a validé et
        écrit un nouveau `profil.json`, cette méthode est appelée sur
        CHAQUE instance vivante pour que CV/lettre de motivation reflètent
        le nouveau profil dès la prochaine génération, sans redémarrage."""
        self.profil_manager = ProfilManager(load_profil_json())

    def _profile_text(self) -> str:
        chunks = self.profil_manager.parse_profile()
        return "\n\n".join(c["text"] for c in chunks)

    def _user_input(self, offer_text: str) -> str:
        return f"PROFIL COMPLET :\n{self._profile_text()}\n\nOFFRE :\n{offer_text}"

    def _real_project_description(self, titre: str) -> str | None:
        """Description réelle du profil pour ce titre de projet exact, ou
        `None` si le titre ne correspond à aucun projet du profil."""
        project = self._real_project_metadata(titre)
        return project.get("description", "").strip() if project else None

    def _real_project_metadata(self, title: str) -> dict | None:
        target = _fold(_single_line(title))
        if not target:
            return None
        matches = [
            chunk["metadata"]
            for chunk in self.profil_manager.parse_profile()
            if chunk["type"] == "project" and _fold(_single_line(chunk["title"])) == target
        ]
        return matches[0] if len(matches) == 1 else None

    def _real_experience_metadata(
        self,
        entreprise: str,
        periode: str = "",
        role: str = "",
        used: set[tuple[str, str, str]] | None = None,
    ) -> dict | None:
        """Métadonnées réelles du profil pour cette entreprise, ou `None`
        si aucune expérience du profil ne correspond. Comparaison par
        sous-chaîne dans les deux sens (accents/casse neutralisés) pour
        tolérer une légère reformulation du nom par le LLM, sans jamais
        faire confiance à sa paraphrase pour le contenu lui-même."""
        cible = _fold(_single_line(entreprise))
        if not cible:
            return None
        source_experiences = [
            chunk["metadata"]
            for chunk in self.profil_manager.parse_profile()
            if chunk["type"] == "experience"
        ]
        candidates = [
            meta for meta in source_experiences
            if _fold(_single_line(meta.get("company", ""))) == cible
        ]
        if not candidates:
            # Tolère une légère abréviation uniquement si elle identifie
            # une seule entrée après prise en compte de la période et du rôle.
            candidates = [
                meta for meta in source_experiences
                if (reelle := _fold(_single_line(meta.get("company", ""))))
                and (cible in reelle or reelle in cible)
            ]
        if not candidates:
            return None

        signature = _period_signature(periode)
        if any(signature):
            exact_period = [
                meta for meta in candidates
                if _period_signature(meta.get("period", "")) == signature
            ]
            if exact_period:
                candidates = exact_period
            elif len(candidates) > 1:
                # Une période inventée ou mal reconnue ne doit pas
                # départager deux expériences du même employeur.
                return None

        role_key = _fold(role)
        exact_role = [
            meta for meta in candidates
            if _fold(meta.get("role", "")) == role_key
        ]
        if role_key and exact_role:
            candidates = exact_role
        elif role_key and len(candidates) > 1:
            return None

        available = [
            meta for meta in candidates
            if used is None or _experience_identity(meta) not in used
        ]
        return available[0] if len(available) == 1 else None

    def _validate_experiences(
        self, experiences: list[CVExperience]
    ) -> list[CVExperience]:
        """Une expérience réelle n'implique pas que CHAQUE chiffre placé
        dedans par le LLM lui appartiennent vraiment : un fait (avec ou
        sans chiffre) d'un stage peut être recopié depuis un autre stage
        réel et sembler crédible. On conserve donc les intitulés, périodes
        et puces provenant du profil exact associé à l'expérience, plutôt
        que de faire confiance à une paraphrase impossible à vérifier
        complètement. Une expérience qui ne correspond à AUCUNE entrée du
        profil est exclue en entier."""
        validated: list[CVExperience] = []
        used: set[tuple[str, str, str]] = set()
        for exp in experiences:
            meta = self._real_experience_metadata(
                exp.entreprise, exp.periode, exp.role, used
            )
            if meta is None:
                continue
            used.add(_experience_identity(meta))
            puces = self._fallback_experience_bullets(meta)
            validated.append(
                CVExperience(
                    role=meta.get("role", exp.role),
                    # Nom réel du profil, jamais celui rendu par le LLM :
                    # un modèle plus petit peut retourner "Servier France
                    # chez Servier France" (le mot "chez" déjà inclus dans
                    # le champ), qui s'affiche ensuite en double une fois
                    # que le code ajoute son propre "chez {entreprise}".
                    entreprise=meta.get("company", exp.entreprise),
                    periode=meta.get("period", exp.periode),
                    puces=puces[:3],
                )
            )

        source_experiences = [
            chunk["metadata"]
            for chunk in self.profil_manager.parse_profile()
            if chunk["type"] == "experience"
        ]
        if len(source_experiences) <= 4:
            for meta in source_experiences:
                identity = _experience_identity(meta)
                if identity in used:
                    continue
                validated.append(
                    CVExperience(
                        role=meta.get("role", ""),
                        entreprise=meta.get("company", ""),
                        periode=meta.get("period", ""),
                        puces=self._fallback_experience_bullets(meta),
                    )
                )
                used.add(identity)

        validated.sort(key=lambda item: _experience_order(item.periode), reverse=True)
        return validated

    @staticmethod
    def _looks_french(text: str) -> bool:
        """Heuristique légère : certaines expériences de profil.json ont
        des `highlights`/`results` rédigés en anglais (jamais traduits),
        jamais vus avant qu'un vrai CV en français ne les affiche tels
        quels (bug réel observé). Pas de dépendance de détection de
        langue pour un cas aussi simple : la quasi-totalité des phrases en
        français de ce profil contiennent un caractère accentué ; celles
        qui n'en contiennent aucun sont, en pratique, systématiquement les
        passages laissés en anglais."""
        return any(ch in text for ch in "éèêëàâäùûüôöîïçÉÈÊÀÂÙÛÔÎÇ")

    def _fallback_experience_bullets(self, meta: dict) -> list[str]:
        """Utilise les faits du profil pour préserver une expérience omise.
        Ne retient highlights/results que s'ils sont en français (cf.
        `_looks_french`) ; sinon, retombe sur les phrases de `description`
        (toujours en français dans ce profil), plutôt que d'afficher de
        l'anglais sur un CV en français."""
        highlights = [h for h in meta.get("highlights", []) if self._looks_french(h)]
        results = [
            str(value) for value in meta.get("results", {}).values()
            if self._looks_french(str(value))
        ]
        description = meta.get("description", "").strip()
        bullets = highlights[:2] if results else highlights[:3]
        bullets.extend(results[: 3 - len(bullets)])
        if len(bullets) < 2 and description:
            sentences = [s.strip() for s in description.split(". ") if s.strip()]
            for sentence in sentences:
                if len(bullets) >= 3:
                    break
                if sentence not in bullets:
                    bullets.append(sentence if sentence.endswith(".") else sentence + ".")
        return bullets[:3]

    def _validate_projets(self, projets: list[CVProjet]) -> list[CVProjet]:
        """Un titre de projet correct n'implique pas une description
        correcte : observé en pratique, le LLM peut reprendre un vrai
        titre du profil mais lui coller une description recopiée d'une
        autre section (ex. une expérience) au lieu du vrai texte du
        projet. On ne fait plus confiance à sa paraphrase : la description
        est remplacée par le texte réel du profil (tronqué à une ligne),
        et un titre qui ne correspond à AUCUN projet réel est exclu plutôt
        que gardé avec une description fabriquée."""
        validated = []
        for p in projets:
            reelle = self._real_project_description(p.titre)
            if reelle is None:
                continue
            if len(reelle) > 220:
                reelle = reelle[:220].rsplit(" ", 1)[0] + "…"
            metadata = self._real_project_metadata(p.titre)
            if metadata is None:
                continue
            validated.append(
                CVProjet(
                    titre=metadata.get("title", p.titre),
                    description=reelle,
                )
            )
        return validated

    def _real_formation(self) -> list[str]:
        """Reprend la formation directement du profil réel, jamais la
        paraphrase du LLM pour `cv.formation` (simple `list[str]`, sans
        validation jusqu'ici contrairement à `experiences`/`projets`) :
        malgré le prompt ("reprends l'établissement et le diplôme
        EXACTEMENT...") et le chunk RAG dédié déjà ajouté pour lui donner
        la vraie donnée (cf. le commentaire dans
        `profil_manager.parse_profile`), le LLM peut encore la reformuler
        ou en omettre une. Contrairement à l'expérience/aux projets, il
        n'y a aucune raison de filtrer la formation par pertinence à
        l'offre (le profil en compte typiquement 1 à 3 entrées, toutes
        attendues dans n'importe quel CV) : on reconstruit la liste en
        entier depuis le profil plutôt que de valider/filtrer la sortie
        du LLM."""
        return [
            f"{chunk['metadata']['degree']} en {chunk['metadata']['field']}, "
            f"{chunk['metadata']['institution']} ({chunk['metadata'].get('period', '?')})"
            for chunk in self.profil_manager.parse_profile()
            if chunk["type"] == "education"
        ]

    def _real_competences(self, proposed: dict[str, list[str]]) -> dict[str, list[str]]:
        """Ne garde que des compétences réellement présentes dans leur
        catégorie du profil ; les noms de catégories viennent aussi du profil."""
        source = self.profil_manager.profil.get("skills", {})
        proposed_by_key = {
            _fold(category): values
            for category, values in proposed.items()
            if isinstance(values, list)
        }
        validated: dict[str, list[str]] = {}
        for category, real_skills in source.items():
            if not isinstance(real_skills, list):
                continue
            selected = {
                _fold(value)
                for value in proposed_by_key.get(_fold(category), [])
                if isinstance(value, str)
            }
            real_values = [value for value in real_skills if isinstance(value, str) and value.strip()]
            kept = [value for value in real_values if _fold(value) in selected]
            if kept:
                validated[category] = list(dict.fromkeys(kept))
        return validated

    def _real_certifications(self, proposed: list[str]) -> list[str]:
        profile_certs = self.profil_manager.profil.get("certifications", {})
        real_titles = [
            _single_line(cert.get("title"))
            for source in ("website", "linkedin")
            for cert in profile_certs.get(source, [])
            if isinstance(cert, dict) and _single_line(cert.get("title"))
        ]
        normalized_proposals = [_fold(item) for item in proposed if isinstance(item, str)]
        selected = [
            title for title in real_titles
            if any(_fold(title) == item or _fold(title) in item for item in normalized_proposals)
        ]
        return list(dict.fromkeys(selected or real_titles))[:3]

    def _real_languages(self) -> list[str]:
        return [
            f"{_single_line(item.get('language'))} : {_single_line(item.get('level'))}"
            for item in self.profil_manager.profil.get("languages", [])
            if isinstance(item, dict) and _single_line(item.get("language"))
        ]

    def _real_interests(self) -> list[str]:
        return list(dict.fromkeys(
            _single_line(item)
            for item in self.profil_manager.profil.get("interests", [])
            if isinstance(item, str) and _single_line(item)
        ))

    def _real_cv_summary(self, offer_context: str) -> str:
        """Résumé CV déterministe : aucune compétence, expérience ou
        qualification ne peut être ajoutée par paraphrase du LLM."""
        profile = self.profil_manager.profil
        education = profile.get("education", [])
        sentences = []
        if education:
            latest = education[0]
            sentence = "Mon parcours comprend"
            degree = _single_line(latest.get("degree"))
            field = _single_line(latest.get("field"))
            institution = _single_line(latest.get("institution"))
            details = " en ".join(value for value in (degree, field) if value)
            if details:
                sentence += f" {details}"
            if institution:
                sentence += f" à {institution}"
            sentences.append(sentence + ".")
        skills = [
            _single_line(skill)
            for values in profile.get("skills", {}).values()
            if isinstance(values, list)
            for skill in values
            if isinstance(skill, str) and _single_line(skill)
        ][:5]
        if skills:
            sentences.append(f"Mes compétences clés incluent {', '.join(skills)}.")
        first_line = _single_line(offer_context.splitlines()[0] if offer_context.splitlines() else "")
        target = _offer_context_value(offer_context, "Intitulé") or first_line
        if target.casefold().startswith(("entreprise :", "lieu :", "contrat :", "description")):
            target = ""
        if target:
            sentences.append(f"Je candidate au poste de {target}.")
        if not sentences:
            return "Mon CV présente les informations vérifiées de mon profil."
        return " ".join(sentences)

    @staticmethod
    def _offer_terms(offer_context: str) -> set[str]:
        ignored = {"avec", "dans", "pour", "chez", "poste", "offre", "the", "and", "with", "from"}
        return {
            word for word in re.findall(r"\w+", _fold(offer_context))
            if len(word) > 3 and word not in ignored
        }

    def _selection_records(self) -> tuple[list[dict], list[dict], list[dict], list[dict]]:
        chunks = self.profil_manager.parse_profile()
        experiences = [chunk["metadata"] for chunk in chunks if chunk["type"] == "experience"]
        projects = [chunk["metadata"] for chunk in chunks if chunk["type"] == "project"]
        skills = [
            {"category": category, "skill": skill}
            for category, values in self.profil_manager.profil.get("skills", {}).items()
            if isinstance(values, list)
            for skill in values
            if isinstance(skill, str) and skill.strip()
        ]
        certifications = [
            cert
            for source in ("website", "linkedin")
            for cert in self.profil_manager.profil.get("certifications", {}).get(source, [])
            if isinstance(cert, dict) and _single_line(cert.get("title"))
        ]
        return experiences, projects, skills, certifications

    def _keyword_selection(self, offer_context: str) -> ApplicationSelection:
        # Côté offre uniquement (jamais côté candidat.e ci-dessous) : une
        # offre qui dit "intelligence artificielle"/"agents IA" doit aussi
        # matcher un intitulé réel disant "Machine Learning", même sans
        # mot commun (cf. `expand_domain_terms`). Élargir aussi le texte du
        # candidat.e romprait la précision du recouvrement (tout ce qui
        # partage un domaine matcherait tout).
        terms = self._offer_terms(offer_context) | expand_domain_terms(offer_context)
        experiences, projects, skills, certifications = self._selection_records()

        def ranked_indices(records: list[dict], text_for, limit: int) -> list[int]:
            ranked = []
            for index, record in enumerate(records):
                text = text_for(record)
                overlap = len(terms & self._offer_terms(text))
                ranked.append((overlap, index))
            ranked.sort(key=lambda item: (item[0], -item[1]), reverse=True)
            return [index for _, index in ranked[:limit]]

        return ApplicationSelection(
            experience_indices=ranked_indices(
                experiences,
                lambda item: " ".join([
                    str(item.get("role", "")), str(item.get("company", "")),
                    str(item.get("description", "")),
                    *[str(value) for value in item.get("highlights", [])],
                ]),
                4,
            ),
            project_indices=ranked_indices(
                projects,
                lambda item: " ".join([
                    str(item.get("title", "")), str(item.get("description", "")),
                    *[str(value) for value in item.get("technologies", [])],
                ]),
                3,
            ),
            skill_indices=ranked_indices(
                skills, lambda item: f"{item['category']} {item['skill']}", 10
            ),
            certification_indices=ranked_indices(
                certifications,
                lambda item: f"{item.get('title', '')} {item.get('issuer', '')}",
                3,
            ),
        )

    @staticmethod
    def _validated_indices(values: list[int], count: int, limit: int) -> list[int]:
        valid = []
        for value in values:
            if isinstance(value, int) and not isinstance(value, bool) and 0 <= value < count and value not in valid:
                valid.append(value)
            if len(valid) >= limit:
                break
        return valid

    def _select_application_items(self, offer_context: str) -> ApplicationSelection:
        fallback = self._keyword_selection(offer_context)
        mode = settings.application_selection_mode
        if mode != "llm":
            return fallback

        experiences, projects, skills, certifications = self._selection_records()
        evidence = {
            "offer": _single_line(offer_context)[:3500],
            "experiences": [
                {
                    "id": index,
                    "role": _single_line(item.get("role")),
                    "company": _single_line(item.get("company")),
                    "period": _single_line(item.get("period")),
                    "facts": _single_line(item.get("description"))[:260]
                    + " " + " ".join(_single_line(value) for value in item.get("highlights", [])[:2]),
                }
                for index, item in enumerate(experiences)
            ],
            "projects": [
                {"id": index, "title": _single_line(item.get("title")),
                 "facts": _single_line(item.get("description"))[:240]}
                for index, item in enumerate(projects)
            ],
            "skills": [
                {"id": index, "category": item["category"], "skill": item["skill"]}
                for index, item in enumerate(skills)
            ],
            "certifications": [
                {"id": index, "title": _single_line(item.get("title")),
                 "issuer": _single_line(item.get("issuer"))}
                for index, item in enumerate(certifications)
            ],
        }
        try:
            selection = self.llm.structured(
                schema=ApplicationSelection,
                system=_SELECTION_SYSTEM,
                user=json.dumps(evidence, ensure_ascii=False),
                num_ctx=4096,
            )
        except Exception:
            return fallback

        llm_experience = self._validated_indices(selection.experience_indices, len(experiences), 4)
        llm_project = self._validated_indices(selection.project_indices, len(projects), 3)
        llm_skill = self._validated_indices(selection.skill_indices, len(skills), 10)

        # FUSION, jamais un remplacement : le LLM peut AJOUTER une entrée que
        # le simple recouvrement lexical aurait manquée (reformulation,
        # nuance), mais ne doit jamais faire DISPARAÎTRE une entrée que le
        # score par mots-clés jugeait déjà pertinente - un CV de candidature
        # réelle ne doit jamais régresser par rapport au plancher
        # déterministe. Le plancher garde la priorité d'ordre (les 4/3/10
        # premières places), le LLM ne complète que s'il reste de la place.
        return ApplicationSelection(
            experience_indices=_merge_indices(fallback.experience_indices, llm_experience, 4),
            project_indices=_merge_indices(fallback.project_indices, llm_project, 3),
            skill_indices=_merge_indices(fallback.skill_indices, llm_skill, 10),
            # Toujours déterministe, même en mode "llm" : constaté en direct,
            # un titre de certification est un texte court et très lexical
            # (ex. "Machine Learning specialisation") - le score par mots-clés
            # le classe correctement en tête pour une offre IA/ML, alors que
            # le LLM local a renvoyé les 3 premières certifications du profil
            # sans rapport avec l'offre, faisant disparaître la plus
            # pertinente d'un CV réel. Ici, rien à gagner à le laisser
            # contribuer, même en complément.
            certification_indices=fallback.certification_indices,
        )

    def _profile_experiences_for_cv(
        self, offer_context: str, selection: ApplicationSelection
    ) -> list[CVExperience]:
        source = [
            chunk["metadata"]
            for chunk in self.profil_manager.parse_profile()
            if chunk["type"] == "experience"
        ]
        indices = list(range(len(source))) if len(source) <= 4 else selection.experience_indices
        proposed = [
            CVExperience(
                role=meta.get("role", ""),
                entreprise=meta.get("company", ""),
                periode=meta.get("period", ""),
                puces=self._fallback_experience_bullets(meta),
            )
            for index in indices[:4]
            for meta in [source[index]]
        ]
        return self._validate_experiences(proposed)

    def _profile_projects_for_cv(self, selection: ApplicationSelection) -> list[CVProjet]:
        projects = [
            chunk for chunk in self.profil_manager.parse_profile()
            if chunk["type"] == "project"
        ]
        proposed = [
            CVProjet(
                titre=chunk["title"],
                description=chunk["metadata"].get("description", ""),
            )
            for index in selection.project_indices[:3]
            for chunk in [projects[index]]
        ]
        return self._validate_projets(proposed)

    # Libellés humains pour les clés techniques de profil.json
    # (`skills.<clé>`, ex. "machine_learning_deep_learning") : jamais
    # affichées telles quelles sur un CV, cf. bug réel observé (catégories
    # en snake_case sur la pièce jointe "postuler par mail").
    _CATEGORY_LABELS = {
        "bayesian_inference": "Inférence bayésienne",
        "machine_learning_deep_learning": "Machine learning & deep learning",
        "computer_vision": "Vision par ordinateur",
        "statistics": "Statistiques",
        "programming_languages": "Langages de programmation",
        "tools_and_frameworks": "Outils & frameworks",
    }

    def _profile_competences_for_cv(self, selection: ApplicationSelection) -> dict[str, list[str]]:
        _, _, skills, _ = self._selection_records()
        proposed: dict[str, list[str]] = {}
        for index in selection.skill_indices[:10]:
            item = skills[index]
            proposed.setdefault(item["category"], []).append(item["skill"])
        validated = self._real_competences(proposed)
        # Relabellisé APRES validation : `_real_competences` valide en
        # comparant aux vraies clés de profil.json (snake_case) et renvoie
        # ces mêmes clés brutes - les traduire avant casserait la
        # comparaison et viderait silencieusement toutes les compétences.
        return {self._CATEGORY_LABELS.get(key, key): values for key, values in validated.items()}

    def _profile_certifications_for_cv(self, selection: ApplicationSelection) -> list[str]:
        _, _, _, certifications = self._selection_records()
        proposed = [
            certifications[index].get("title", "")
            for index in selection.certification_indices[:3]
        ]
        return self._real_certifications(proposed)

    def draft_cv(self, offer_text: str) -> CVContent:
        selection = self._select_application_items(offer_text)
        return CVContent(
            profil=self._real_cv_summary(offer_text),
            experiences=self._profile_experiences_for_cv(offer_text, selection),
            projets=self._profile_projects_for_cv(selection),
            competences=self._profile_competences_for_cv(selection),
            formation=self._real_formation(),
            certifications=self._profile_certifications_for_cv(selection),
            langues=self._real_languages(),
            centres_interet=self._real_interests(),
        )

    @staticmethod
    def contact_header() -> str:
        """En-tête assemblé à partir de `settings`, jamais généré par le
        LLM (une identité inventée est un risque bien plus grave qu'un
        champ manquant). Un champ non renseigné dans `.env` est
        simplement omis, pas remplacé par un espace réservé."""
        lignes = [
            settings.user_full_name,
            settings.user_city,
            settings.user_phone,
            settings.user_contact_email,
            f"LinkedIn : {settings.user_linkedin}" if settings.user_linkedin else None,
        ]
        return "\n".join(l for l in lignes if l)

    def draft_cover_letter(self, offer_text: str, *, short: bool = False) -> str:
        corps = self._grounded_cover_letter(offer_text, short=short)
        if short:
            return corps
        header = self.contact_header()
        return f"{header}\n\n{corps}" if header else corps

    def draft_cover_letter_stream(self, offer_text: str, *, short: bool = False) -> Iterator[str]:
        """Diffuse le texte vérifié par petits fragments, sans génération LLM."""
        body = self._grounded_cover_letter(offer_text, short=short)
        for start in range(0, len(body), 96):
            yield body[start:start + 96]

    def _grounded_cover_letter(self, offer_context: str, *, short: bool) -> str:
        """Construit une lettre uniquement depuis des faits du profil et
        des métadonnées de l'offre, sans laisser le LLM ajouter des faits."""
        selection = self._select_application_items(offer_context)
        lines = offer_context.splitlines()
        title = _single_line(lines[0]) if lines else ""
        if title.casefold().startswith("intitulé :"):
            title = _single_line(title.split(":", 1)[1])
        if title.casefold().startswith(("entreprise :", "lieu :", "contrat :", "description")):
            title = ""
        company = _offer_context_value(offer_context, "Entreprise")
        target = f"{title or 'cette offre'}"
        if company:
            target += f" chez {company}"

        paragraphs = [f"Objet : Candidature au poste de {title or 'cette offre'}.", "Madame, Monsieur,"]
        paragraphs.append(f"Je vous adresse ma candidature pour {target}.")

        education = self.profil_manager.profil.get("education", [])
        if education:
            item = education[0]
            degree = _single_line(item.get("degree"))
            field = _single_line(item.get("field"))
            institution = _single_line(item.get("institution"))
            period = _single_line(item.get("period"))
            facts = " en ".join(value for value in (degree, field) if value)
            if institution:
                facts += f", {institution}"
            if period:
                facts += f" ({period})"
            if facts:
                paragraphs.append(f"Mon parcours comprend {facts}.")

        experiences = [
            chunk["metadata"]
            for chunk in self.profil_manager.parse_profile()
            if chunk["type"] == "experience"
        ]
        selected_experiences = [
            experiences[index]
            for index in selection.experience_indices[: (1 if short else 2)]
            if 0 <= index < len(experiences)
        ]
        for meta in selected_experiences:
            role = _single_line(meta.get("role"))
            employer = _single_line(meta.get("company"))
            period = _single_line(meta.get("period"))
            description = _single_line(meta.get("description"))
            # Deux phrases COMPLETES et INDEPENDANTES plutôt qu'une seule
            # phrase fusionnée ("En tant que X (période), <description>") :
            # la description de profil.json ne continue pas forcément
            # grammaticalement après une virgule (elle commence souvent par
            # sa propre majuscule, ex. "Stage de quatre mois..."), ce qui
            # produisait une phrase cassée. Deux phrases séparées restent
            # grammaticalement correctes quelle que soit la forme du texte
            # source.
            intro = "J'ai occupé le poste de" if role else "J'ai travaillé"
            if role:
                intro += f" {role}"
            if employer:
                intro += f" chez {employer}"
            if period:
                intro += f" ({period})"
            paragraphs.append(intro + ".")
            if description:
                paragraphs.append(description)
            # `highlights` (quand présent) est en anglais dans profil.json
            # pour certaines expériences : jamais mélangé à une lettre en
            # français, `description` suffit toujours comme fait source.

        _, _, skills, _ = self._selection_records()
        chosen_skills = [
            skills[index]["skill"]
            for index in selection.skill_indices[:5]
            if 0 <= index < len(skills)
        ]
        if chosen_skills:
            paragraphs.append(f"Je maîtrise notamment {', '.join(chosen_skills)}.")

        if short:
            paragraphs.extend(["Je reste à votre disposition pour un échange.", "Cordialement,", settings.user_name])
        else:
            paragraphs.extend([
                "Je reste à votre disposition pour un entretien.",
                "Veuillez agréer, Madame, Monsieur, l'expression de mes salutations distinguées.",
                settings.user_name,
            ])
        return "\n\n".join(paragraphs)

    def refine_cover_letter(self, previous_letter: str, offer_text: str) -> str:
        """Regénère la lettre depuis les faits sources au lieu de paraphraser
        un texte antérieur qui pourrait contenir une affirmation inventée."""
        del previous_letter
        corps = self._grounded_cover_letter(offer_text, short=False)
        header = self.contact_header()
        return f"{header}\n\n{corps}" if header else corps

    def refine_cover_letter_stream(self, previous_letter: str, offer_text: str) -> Iterator[str]:
        """Version diffusée de `refine_cover_letter()`, ne yield que le
        corps, même contrat que `draft_cover_letter_stream()`."""
        del previous_letter
        body = self._grounded_cover_letter(offer_text, short=False)
        for start in range(0, len(body), 96):
            yield body[start:start + 96]

    def draft_email_envoi(self, offer_name: str) -> str:
        return self.llm.text(
            system=SYSTEM_EMAIL_ENVOI.format(user_name=settings.user_name),
            user=offer_name,
        )
